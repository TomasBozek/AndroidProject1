private fun item(
    id: String,
    name: String,
    category: ItemCategory,
    condition: ItemCondition,
    quantity: Int,
    priceMinor: Long,
    tags: Set<ItemTag>,
    owner: String,
    notes: String,
    acquiredOn: LocalDate? = null,
    insured: Boolean = false,
) = Item(
    id = "item-$id",
    name = name,
    category = category,
    condition = condition,
    quantity = quantity,
    priceMinor = priceMinor,
    acquiredOn = acquiredOn,
    insured = insured,
    tags = tags,
    owner = owner,
    imageUrl = "https://example.com/inventory/$id.jpg",
    notes = notes,
)
