// An included build, not a module: it produces the `convention.*` plugins the modules apply, so it
// has to be configured before any of them. See the root settings.gradle.kts's pluginManagement.
pluginManagement {
    repositories {
        google {
            content {
                includeGroupByRegex("com\\.android.*")
                includeGroupByRegex("com\\.google.*")
                includeGroupByRegex("androidx.*")
            }
        }
        mavenCentral()
        gradlePluginPortal()
    }
}

